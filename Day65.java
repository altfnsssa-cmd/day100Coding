import java.util.Scanner;

public class Day65 {
    public static void main(String[] args) {

        Scanner caca = new Scanner(System.in);

        int n;

        System.out.print("Masukkan jumlah garis: ");
        n = caca.nextInt();

        for (int i = 1; i <= n; i++) {
            System.out.println("*");
        }

      
    }
}
