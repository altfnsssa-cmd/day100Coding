public class Main {
public static void main(String[] args) {

    // \n pindah baris \ ke baris berikutnya 
    System.out.println("Halo\nCaca");

    // \t memberikan jarak yang cukup lebar, seperti menekan tombol tab
    System.out.println("Hai nama saya\tCaca"); 
    System.out.println("Umur saya\t18 tahun");

    // \"" menampilkan tanda petik digunakan untuk menandai awal dan akhir teks
    System.out.println("Dia berkata, \"Aku suka bunga.\"");

    // \\ digunakan jika kita ingin menampilkan backlash\. 
    System.out.println("C:\\Caca\\Imut");

    // \b berarti mundur satu karakter 
    System.out.println("Cacaa\b");

    // \r untuk kembali keawal baris 
    System.out.println("Hai salam\r kenal");


    }
}
