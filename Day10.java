public class day10 {
    public static void main(String[] args) {

        // Batas minimal dan maksimal tipe data adalah nilai terkecil dan terbesar yang
        // dapat disimpan
        // oleh suatu tipe data dalam program. Setiap tipe data memiliki kapasitas
        // penyimpanan yang berbeda

        byte angka1 = -128; // Batas minimal
        byte angka2 = 127; // Batas maksimal
        byte angka3 = 50; // Nilai di antara batas

        System.out.println("angka1: "+ angka1);
        System.out.println("angka2: "+ angka2);
        System.out.println("angka3: "+ angka3);

    }
}
